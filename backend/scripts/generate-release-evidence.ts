import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { REQUIREMENT_COVERAGE_GROUPS } from '../src/release/requirement-catalog'
import { ALL_DOMAIN_EVENT_TYPES, DOMAIN_EVENT_CATALOG } from '../src/shared/outbox'
import { ALL_QUEUE_NAMES } from '../src/shared/queue'
import { ALL_SCHEDULED_JOB_NAMES, SCHEDULED_JOB_CATALOG } from '../src/workers/scheduled-jobs'

const root = join(import.meta.dir, '..')
const workspace = join(root, '..')
const promptPath = join(workspace, 'innovation_backend_master_prompt.md')
const generatedDirectory = join(root, 'docs', 'generated')
const matrixPath = join(generatedDirectory, 'requirement-matrix.md')
const reportPath = join(root, 'docs', 'IMPLEMENTATION_REPORT.md')
const checkOnly = process.argv.includes('--check')

interface PromptSection {
  readonly number: number
  readonly title: string
}

function filesUnder(directory: string, predicate: (path: string) => boolean): string[] {
  const found: string[] = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) found.push(...filesUnder(path, predicate))
    else if (predicate(path)) found.push(path)
  }
  return found.sort()
}

function parsePromptSections(prompt: string): PromptSection[] {
  return [...prompt.matchAll(/^#{1,2} (\d+)\. (.+)$/gm)].map((match) => ({
    number: Number(match[1]),
    title: match[2]?.trim() ?? '',
  }))
}

function markdownPath(path: string): string {
  const absolute = join(root, path)
  const display = path.replace(/^\.\.\//, 'workspace/')
  const target = relative(generatedDirectory, absolute).replaceAll('\\', '/')
  return `[${display}](${target})`
}

function assertCatalogue(sections: readonly PromptSection[]): void {
  const known = new Set(sections.map((section) => section.number))
  const classified = new Map<number, string>()

  for (const group of REQUIREMENT_COVERAGE_GROUPS) {
    if (group.enforcement.length === 0 || group.provingTests.length === 0) {
      throw new Error(`Requirement group ${group.id} has no implementation or proving test.`)
    }
    for (const section of group.sections) {
      if (!known.has(section))
        throw new Error(`Requirement group ${group.id} names unknown §${section}.`)
      const duplicate = classified.get(section)
      if (duplicate !== undefined) {
        throw new Error(
          `Master prompt §${section} is classified by both ${duplicate} and ${group.id}.`,
        )
      }
      classified.set(section, group.id)
    }
    for (const path of [...group.enforcement, ...group.provingTests]) {
      if (!existsSync(join(root, path))) {
        throw new Error(`Requirement group ${group.id} cites missing evidence: ${path}`)
      }
    }
  }

  const missing = sections.filter((section) => !classified.has(section.number))
  if (missing.length > 0) {
    throw new Error(
      `Unclassified master-prompt sections: ${missing.map((item) => `§${item.number}`).join(', ')}`,
    )
  }
}

const prompt = readFileSync(promptPath, 'utf8')
const sections = parsePromptSections(prompt)
assertCatalogue(sections)

const migrations = readdirSync(join(root, 'prisma', 'migrations'), { withFileTypes: true }).filter(
  (entry) => entry.isDirectory(),
)
const tests = filesUnder(join(root, 'tests'), (path) => path.endsWith('.test.ts'))
const modules = readdirSync(join(root, 'src', 'modules'), { withFileTypes: true }).filter((entry) =>
  entry.isDirectory(),
)
const openapi = JSON.parse(readFileSync(join(root, 'docs', 'openapi.json'), 'utf8')) as {
  paths?: Record<string, Record<string, unknown>>
}
const openApiPaths = Object.keys(openapi.paths ?? {})
const openApiOperations = Object.values(openapi.paths ?? {}).reduce(
  (count, item) =>
    count +
    Object.keys(item).filter((method) =>
      ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'].includes(method),
    ).length,
  0,
)
const promptDigest = createHash('sha256').update(prompt).digest('hex')

const groupBySection = new Map(
  REQUIREMENT_COVERAGE_GROUPS.flatMap((group) =>
    group.sections.map((section) => [section, group] as const),
  ),
)

const matrixRows = sections.map((section) => {
  const group = groupBySection.get(section.number)
  if (group === undefined) throw new Error(`Missing classification for §${section.number}.`)
  return `| §${section.number} ${section.title} | ${group.status} | ${group.enforcement.map(markdownPath).join('<br>')} | ${group.provingTests.map(markdownPath).join('<br>')} | ${group.note} |`
})

