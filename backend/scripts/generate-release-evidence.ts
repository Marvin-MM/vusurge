function emit(path: string, content: string): void {
  if (checkOnly) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      throw new Error(`${relative(root, path)} is stale. Run bun run evidence:generate.`)
    }
    return
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content, 'utf8')
}

emit(matrixPath, matrix)
emit(reportPath, report)

if (!checkOnly) {
  console.log(`Generated ${relative(root, matrixPath)} and ${relative(root, reportPath)}.`)
} else {
  console.log('Generated requirement evidence is current and every numbered section is classified.')
}
